import re
from functools import lru_cache

# слова: кириллица (включая казахские буквы), латиница, цифры; десятичные числа вроде 6.5 – одним токеном
TOKEN_RE = re.compile(r"[0-9]+(?:[.,][0-9]+)?|[a-zа-яёәғқңөұүһі]+", re.IGNORECASE)

# буквы, которых нет в русском алфавите: слово с ними – казахское, русский морфоанализатор его исказит
KAZAKH_LETTERS = set("әғқңөұүһі")
CYRILLIC_RE = re.compile(r"[а-яё]")

