STOPWORDS = STOPWORDS_RU | STOPWORDS_KK | STOPWORDS_EN

# вопросительные слова несут смысл вопроса («где расписание» и «когда расписание» – разные интенты),
# поэтому в облегчённом списке они остаются в тексте
QUESTION_WORDS = {
    "как", "когда", "где", "куда", "сколько", "какой", "какая", "кто", "что", "зачем", "можно",
    "нельзя", "есть", "нет", "қандай", "қалай", "қашан", "қайда", "қанша", "кім", "не", "бар", "жоқ",
    "what", "which", "who", "when", "where", "why", "how", "can",
}
STOPWORDS_NO_QUESTIONS = STOPWORDS - QUESTION_WORDS


# морфоанализатор грузится один раз и только при первой лемматизации (около 15 МБ словарей)
@lru_cache(maxsize=1)
def _morph():
    import pymorphy3

    return pymorphy3.MorphAnalyzer()


@lru_cache(maxsize=100_000)
def lemma(token: str) -> str:
    # русские слова приводим к начальной форме; казахские и латиница остаются как есть –
    # для казахского нет лёгкого лемматизатора, словоформы покрывают символьные n-граммы
    if not CYRILLIC_RE.search(token) or KAZAKH_LETTERS & set(token):
        return token
    return _morph().parse(token)[0].normal_form


def normalize(text: str) -> str:
    return text.lower().replace("ё", "е")


def tokenize(text: str) -> list[str]:
    return TOKEN_RE.findall(normalize(text))


# полный конвейер предобработки: нормализация, токенизация, лемматизация, удаление стоп-слов.
# stopwords: None – не удалять, "all" – стандартный список, "no_questions" – без вопросительных слов
def preprocess(text: str, lemmatize: bool = True, stopwords: str | None = None) -> str:
    tokens = tokenize(text)
    if lemmatize:
        tokens = [lemma(t) for t in tokens]
    if stopwords == "all":
        tokens = [t for t in tokens if t not in STOPWORDS]
    elif stopwords == "no_questions":
        tokens = [t for t in tokens if t not in STOPWORDS_NO_QUESTIONS]
    return " ".join(tokens)


# пакетная версия для sklearn-конвейера (FunctionTransformer): функция модульного уровня,
# поэтому сохранённая модель загружается в бэкенде с той же самой предобработкой
def preprocess_batch(texts, lemmatize: bool = True, stopwords: str | None = None) -> list[str]:
    return [preprocess(t, lemmatize, stopwords) for t in texts]
